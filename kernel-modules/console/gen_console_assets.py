#!/usr/bin/env python3
"""Generate kernel-modules/console/fonts.h and tux80.h from the kernel source tree (read-only copies of GPL-2.0 data):
  lib/fonts/font_ter16x32.c, font_sun12x22.c, font_10x18.c   256 glyphs, one 2-byte row per scan line (MSB = leftmost pixel)
  drivers/video/logo/logo_linux_clut224.ppm                  the standard 224-colour Linux boot logo (Tux), 80x80, ASCII P3

usage: 380_gen_console_assets.py <kernel-common-dir> <out-dir>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]

# ---- fonts
FONTS = (("font_ter16x32", "Terminus 16x32", 16, 32), ("font_sun12x22", "Sun 12x22", 12, 22), ("font_10x18", "10x18", 10, 18))
HDR = ("/* SPDX-License-Identifier: GPL-2.0 */\n"
       "/* Bitmap fonts copied from the kernel's lib/fonts/font_xxx.c files (GPL-2.0): 256 glyphs, every glyph row is two bytes, the most significant\n"
       " * bit is the leftmost pixel.  Generated by scripts/380_gen_console_assets.py. */\n")
with open(out + "/fonts.h", "w", encoding="utf-8", newline="\n") as f:
    f.write(HDR)
    for name, label, gw, gh in FONTS:
        text = open(src + "/lib/fonts/%s.c" % name, encoding="utf-8").read()
        mark = "{ 0, 0, FONTDATAMAX, 0 }, {"
        start = text.index(mark)
        end = text.index("};", start)
        body = re.sub(r"/\*.*?\*/", "", text[start + len(mark):end], flags=re.S)
        vals = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body)]
        assert len(vals) == 256 * 2 * gh, (name, len(vals))
        f.write("\n/* %s */\nstatic const unsigned char %s[256 * %d] = {\n" % (label, name, 2 * gh))
        for i in range(0, len(vals), 16):
            f.write("\t" + ", ".join("0x%02x" % v for v in vals[i:i + 16]) + ",\n")
        f.write("};\n")
        print("font %-14s %dx%d: %d bytes" % (name, gw, gh, len(vals)))

# ---- Tux
toks = re.sub(r"#.*", "", open(src + "/drivers/video/logo/logo_linux_clut224.ppm", encoding="utf-8").read()).split()
assert toks[0] == "P3"
w, h, mx = int(toks[1]), int(toks[2]), int(toks[3])
assert (w, h, mx) == (80, 80, 255), (w, h, mx)
px = [int(x) for x in toks[4:]]
assert len(px) == w * h * 3
pal = []
idx = []
for i in range(w * h):
    c = tuple(px[3 * i:3 * i + 3])
    if c not in pal:
        pal.append(c)
    idx.append(pal.index(c))
assert len(pal) <= 256, len(pal)
with open(out + "/tux80.h", "w", encoding="utf-8", newline="\n") as f:
    f.write("/* SPDX-License-Identifier: GPL-2.0 */\n/* The standard Linux boot logo (Tux), 80x80, from the kernel's drivers/video/logo/logo_linux_clut224.ppm (GPL-2.0),\n * palette + one index byte per pixel.  Generated by scripts/380_gen_console_assets.py. */\n")
    f.write("#define TUX_W 80\n#define TUX_H 80\n#define TUX_NCOL %d\n" % len(pal))
    f.write("static const unsigned char tux_pal[TUX_NCOL][3] = {\n")
    for c in pal:
        f.write("\t{ %d, %d, %d },\n" % c)
    f.write("};\nstatic const unsigned char tux_idx[TUX_W * TUX_H] = {\n")
    for i in range(0, len(idx), 20):
        f.write("\t" + ", ".join(str(v) for v in idx[i:i + 20]) + ",\n")
    f.write("};\n")
print("tux %dx%d with %d colours; background pixel (0,0) = %s" % (w, h, len(pal), pal[idx[0]]))
